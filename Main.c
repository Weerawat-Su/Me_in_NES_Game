#define LASER_BOT_ROW  25

#define BOSS_MAX_HP 40

typedef struct {
  byte xpos;
  byte ypos;
  signed char dx;
  signed char dy;
  byte homing_timer; // >0 = กำลังเลี้ยวตามผู้เล่นอยู่ (มิสไซล์ตามรอย)
} Missile;

typedef struct {
  byte x;
  byte y;
  byte name;
  byte tag;
} Sprite;

Missile missiles[NMISSILES];
Sprite vsprites[16];

// GAME VARIABLES
byte player_x;
const byte player_y = 190;
byte player_hp = 3;
byte player_invuln = 0;

// BOSS VARIABLES
byte boss_x = 104; // ปรับตำแหน่งแกน X นิดหน่อยให้บอสอยู่กลางจอ (40px width)
byte boss_y = 40;
signed char boss_dx = 1;
byte boss_hp = BOSS_MAX_HP;
byte boss_state = 0; 
byte boss_timer = 0;
byte boss_attack_pattern = 0; 

// LASER (CORNER-PINCH BEAM) VARIABLES
byte laser_phase = 0;      // 0=ไม่มี, 1=วาดเส้นไกด์, 2=ยิงลำแสงหนา, 3=ลบเส้น
byte laser_row = 0;        // แถวปัจจุบันที่กำลังวาด/ลบ
byte laser_fire_timer = 0; // เวลาที่ลำแสงยิงเต็มค้างไว้ (ใช้เช็คโดนผู้เล่น)

void draw_ui() {
  static char hp_buf[16];

  // Title: COM EN NPU BOSS
  const char title[15] = {
    CHAR('C'), CHAR('O'), CHAR('M'), CHAR(' '),
    CHAR('E'), CHAR('N'), CHAR(' '),
    CHAR('N'), CHAR('P'), CHAR('U'), CHAR(' '),
    CHAR('B'), CHAR('O'), CHAR('S'), CHAR('S')
  };
  vrambuf_put(NTADR_A(1, 1), title, 15);

  // Boss Health: HP: 40/40
  hp_buf[0] = CHAR('H'); 
  hp_buf[1] = CHAR('P'); 
  hp_buf[2] = CHAR(':');
  hp_buf[3] = CHAR(' ');
  hp_buf[4] = CHAR('0' + (boss_hp / 10));
  hp_buf[5] = CHAR('0' + (boss_hp % 10));
  hp_buf[6] = CHAR('/');
  hp_buf[7] = CHAR('0' + (BOSS_MAX_HP / 10));
  hp_buf[8] = CHAR('0' + (BOSS_MAX_HP % 10));
  vrambuf_put(NTADR_A(21, 1), hp_buf, 9);

  // Player Life: PL: 3
  hp_buf[0] = CHAR('P'); hp_buf[1] = CHAR('L'); hp_buf[2] = CHAR(':');
  hp_buf[3] = CHAR('0' + player_hp);
  vrambuf_put(NTADR_A(1, 26), hp_buf, 4);
}

void clrobjs() {
  byte i;
  memset(vsprites, 0, sizeof(vsprites));
  for (i = 0; i < 16; i++) vsprites[i].y = YOFFSCREEN;
  for (i = 0; i < NMISSILES; i++) missiles[i].ypos = YOFFSCREEN;
}

void copy_sprites() {
  byte i;
  byte oamid = 0;

  // 1. Draw Player
  if (player_invuln % 4 < 2) {
    oamid = oam_spr(player_x, player_y, NAME_SHIP, COLOR_PLAYER, oamid);
  }

  // 2. Draw Explosions
  if (vsprites[BOOMSPRITE].y != YOFFSCREEN) {
    oamid = oam_spr(vsprites[BOOMSPRITE].x, vsprites[BOOMSPRITE].y, 
                    vsprites[BOOMSPRITE].name, COLOR_EXPLOSION, oamid);
  }

  // 3. Draw Boss (40x40 pixels / 5x5 tiles)
  if (boss_hp > 0) {
    byte row, col;
    for (row = 0; row < 5; row++) {
      for (col = 0; col < 5; col++) {
        oamid = oam_spr(
          boss_x + (col * 8), 
          boss_y + (row * 8), 
          NAME_ENEMY + (row * 5) + col, 
          COLOR_ATTACKER, 
          oamid
        );
      }
    }
  }

  // 4. Draw Missiles & Bullets
  for (i = 0; i < NMISSILES; i++) {
    if (missiles[i].ypos != YOFFSCREEN) {
      oamid = oam_spr(missiles[i].xpos, missiles[i].ypos, NAME_MISSILE,
                      (i == PLYRMISSILE) ? COLOR_MISSILE : COLOR_BOMB,
                      oamid);
    }
  }

  oam_hide_rest(oamid);
}

void move_player() {
  byte joy = pad_poll(0);
  if ((joy & PAD_LEFT) && player_x > 16) player_x -= 2;
  if ((joy & PAD_RIGHT) && player_x < 224) player_x += 2;
  
  if ((joy & PAD_A) && missiles[PLYRMISSILE].ypos == YOFFSCREEN) {
    missiles[PLYRMISSILE].ypos = player_y - 8;
    missiles[PLYRMISSILE].xpos = player_x + 2;
    missiles[PLYRMISSILE].dy = -5;
    missiles[PLYRMISSILE].dx = 0;
  }

  if (player_invuln > 0) player_invuln--;
}

void boss_fire_bullet_h(signed char dx, signed char dy, byte homing) {
  byte i;
  for (i = 0; i < NMISSILES - 1; i++) {
    if (missiles[i].ypos == YOFFSCREEN) {
      // ตั้งให้จุดเกิดกระสุนอยู่ตรงกลางด้านล่างของบอส 40x40
      missiles[i].xpos = boss_x + 16;
      missiles[i].ypos = boss_y + 32;
      missiles[i].dx = dx;
      missiles[i].dy = dy;
      missiles[i].homing_timer = homing;
      break;
    }
  }
}

void boss_fire_bullet(signed char dx, signed char dy) {
  boss_fire_bullet_h(dx, dy, 0);
}

void boss_fire_spread5() {
  boss_fire_bullet(-2, 3);
  boss_fire_bullet(-1, 4);
  boss_fire_bullet(0,  4);
  boss_fire_bullet(1,  4);
  boss_fire_bullet(2,  3);
}

void boss_fire_spread2() {
  boss_fire_bullet(-1, 4);
  boss_fire_bullet(1,  4);
}

void boss_fire_single() {
  boss_fire_bullet(0, 4);
}

// --- รูปแบบใหม่ 1: ฝนดาวตก - กระสุนสุ่มตกลงมาจากด้านบนจำนวนมาก แต่เว้นช่องว่างให้หลบได้ ---
void boss_fire_meteor() {
  byte i;
  byte rx = 20 + (rand() % 200); // สุ่มตำแหน่ง X ในกรอบสนามเล่น
  for (i = 0; i < NMISSILES - 1; i++) {
    if (missiles[i].ypos == YOFFSCREEN) {
      missiles[i].xpos = rx;
      missiles[i].ypos = 12;              // เกิดเหนือขอบจอ
      missiles[i].dx = 0;
      missiles[i].dy = 2 + (rand() % 2);  // ความเร็วตกไม่เท่ากันเล็กน้อยให้ดูเป็นห่ากระสุน
      missiles[i].homing_timer = 0;
      break;
    }
  }
}

// --- รูปแบบใหม่ 2: กระสุนตามรอยผู้เล่น 1 นัด เลี้ยวตามสั้นๆ แล้วพุ่งตรง (คล้ายมิสไซล์ล็อกเป้าเบาๆ) ---
// HOMING_TIME = จำนวนเฟรมที่ "เลี้ยวตาม" ก่อนจะหยุดเลี้ยวแล้วพุ่งตรงต่อ
// 60 เฟรม = 1 วินาที เดิมตั้งไว้ 120 (2 วิ) ซึ่งเลี้ยวตามนานเกินจนดูไม่เป็นธรรมชาติ
// ปรับให้สั้นลงเหลือ 20 เฟรม (ประมาณ 1/3 วิ) ยิงไปนิดเดียวแล้วล็อกทิศทาง
#define HOMING_TIME 20
void boss_fire_homing1() {
  boss_fire_bullet_h(0, 3, HOMING_TIME);
  boss_fire_bullet_h(0, 5, HOMING_TIME);
}

// --- รูปแบบใหม่ 3: ลำแสงบีบมุม (Corner-Pinch Laser) ---
// เฟส 1 วาดเส้นไกด์บางๆ ทีละแถวจากบนลงล่างเพื่อเตือนตำแหน่ง
// เฟส 2 วาดซ้ำด้วยลำแสงหนา (ทำให้ "เส้นใหญ่ขึ้น") แล้วค้างไว้เพื่อทำดาเมจ
// เฟส 3 ลบเส้นออกทีละแถว กลับสู่สถานะปกติ
void laser_draw_row(byte tile, byte row) {
  char buf[LASER_WIDTH];
  memset(buf, tile, LASER_WIDTH);
  vrambuf_put(NTADR_A(LASER_COL_A, row), buf, LASER_WIDTH);
  vrambuf_put(NTADR_A(LASER_COL_B, row), buf, LASER_WIDTH);
}

void laser_clear_row(byte row) {
  char buf[LASER_WIDTH];
  memset(buf, BLANK, LASER_WIDTH);
  vrambuf_put(NTADR_A(LASER_COL_A, row), buf, LASER_WIDTH);
  vrambuf_put(NTADR_A(LASER_COL_B, row), buf, LASER_WIDTH);
}

void boss_start_laser() {
  laser_phase = 1;
  laser_row = LASER_TOP_ROW;
  laser_fire_timer = 0;
}

void update_laser() {
  if (laser_phase == 0) return;

  if (laser_phase == 1) {               // วาดเส้นไกด์บาง ทีละแถว
    if (laser_row <= LASER_BOT_ROW) {
      laser_draw_row(NAME_LASER_THIN, laser_row);
      laser_row++;
    }
    if (laser_row > LASER_BOT_ROW) {
      laser_phase = 2;
      laser_row = LASER_TOP_ROW;
    }
  }
  else if (laser_phase == 2) {          // เส้นใหญ่ขึ้น = กำลังยิงจริง
    if (laser_row <= LASER_BOT_ROW) {
      laser_draw_row(NAME_LASER_THICK, laser_row);
      laser_row++;
      if (laser_row > LASER_BOT_ROW) laser_fire_timer = 30; // ค้างยิงเต็มเส้น 30 เฟรม
    } else if (laser_fire_timer > 0) {
      laser_fire_timer--;
      if (laser_fire_timer == 0) {
        laser_phase = 3;
        laser_row = LASER_TOP_ROW;
      }
    }
  }
  else if (laser_phase == 3) {          // ลบเส้นออกทีละแถว
    if (laser_row <= LASER_BOT_ROW) {
      laser_clear_row(laser_row);
      laser_row++;
    }
    if (laser_row > LASER_BOT_ROW) {
      laser_phase = 0;
    }
  }
}

// ผู้เล่นโดนลำแสงหรือไม่ (นับเฉพาะตอนลำแสงหนาวาดครบและกำลังค้างยิงอยู่)
char player_in_laser() {
  byte px_tile = player_x / 8;
  if (laser_phase != 2 || laser_fire_timer == 0) return 0;
  if (px_tile >= LASER_COL_A && px_tile < LASER_COL_A + LASER_WIDTH) return 1;
  if (px_tile >= LASER_COL_B && px_tile < LASER_COL_B + LASER_WIDTH) return 1;
  return 0;
}

void update_boss() {
  if (boss_hp == 0) return;

  boss_timer++;

  if (boss_state == 0) { 
    // ระหว่างยิงลำแสงบีบมุม ให้บอสหยุดนิ่งไม่เดิน เพื่อไม่ให้ตำแหน่งลำแสงเพี้ยนจากจุดยิง
    if (boss_attack_pattern != 5 || laser_phase == 0) {
      boss_x += boss_dx;
      if (boss_x > 190 || boss_x < 20) boss_dx = -boss_dx; // ปรับขอบเขตเดินเพื่อรองรับความกว้าง 40px
    }

    if (boss_attack_pattern == 0) {
      if ((boss_timer % 60) < 30 && (boss_timer % 6) == 0) {
        boss_fire_single();
      }
    } 
    else if (boss_attack_pattern == 1) {
      if (boss_timer == 30) {
        boss_fire_spread5();
      }
    } 
    else if (boss_attack_pattern == 2) {
      if (boss_timer == 20 || boss_timer == 50) {
        boss_fire_spread2();
      }
    }
    else if (boss_attack_pattern == 3) {
      // ฝนดาวตก: โปรยกระสุนจากด้านบนถี่ๆ ในช่วงต้นของแพทเทิร์น เว้นช่วงท้ายให้หายใจ
      if (boss_timer < 90 && (boss_timer % 10) == 0) {
        boss_fire_meteor();
      }
    }
    else if (boss_attack_pattern == 4) {
      // กระสุนตามรอยผู้เล่น 1 นัด ยิง 2 ครั้งในแพทเทิร์นนี้
      if (boss_timer == 20 || boss_timer == 70) {
        boss_fire_homing1();
      }
    }
    else if (boss_attack_pattern == 5) {
      // ลำแสงบีบมุม: เริ่มวาดเส้นไกด์ตอนต้นแพทเทิร์น
      if (boss_timer == 10) {
        boss_start_laser();
      }
    }

    {
      // ลำแสงใช้เวลานานกว่ารูปแบบอื่น จึงให้ระยะเวลาแพทเทิร์นยาวขึ้นเป็นพิเศษ
      byte pattern_duration = (boss_attack_pattern == 5) ? 140 : 90;
      if (boss_timer > pattern_duration) {
        boss_timer = 0;
        boss_attack_pattern = (boss_attack_pattern + 1) % 6;

        if (boss_attack_pattern == 0) {
          boss_state = 1;
        }
      }
    }
  } 
  else if (boss_state == 1) { 
    boss_y += 4;
    if (boss_y >= 160) { // ปรับระยะโฉบลงมานิดหน่อยไม่ให้โดนขอบล่างเกินไป
      boss_state = 2;
    }
  } 
  else if (boss_state == 2) { 
    boss_y -= 2;
    if (boss_y <= 40) {
      boss_y = 40;
      boss_state = 0;
      boss_timer = 0;
    }
  }
}

void move_missiles() {
  byte i;
  for (i = 0; i < NMISSILES; i++) {
    if (missiles[i].ypos != YOFFSCREEN) {

      // --- กระสุนเลี้ยวตามผู้เล่น (homing) เฉพาะช่วง 2 วินาทีแรก จากนั้นพุ่งตรง ---
      if (missiles[i].homing_timer > 0) {
        missiles[i].homing_timer--;
        if (missiles[i].xpos < player_x && missiles[i].dx < 2) missiles[i].dx++;
        else if (missiles[i].xpos > player_x && missiles[i].dx > -2) missiles[i].dx--;
      }

      missiles[i].xpos += missiles[i].dx;
      missiles[i].ypos += missiles[i].dy;

      if (missiles[i].ypos > 220 || missiles[i].ypos < 10 || 
          missiles[i].xpos > 240 || missiles[i].xpos < 10) {
        missiles[i].ypos = YOFFSCREEN;
      }
    }
  }
}

void check_collisions() {
  byte i;
  byte mx = missiles[PLYRMISSILE].xpos;
  byte my = missiles[PLYRMISSILE].ypos;

  // กระสุนผู้เล่นโดนบอส (เปลี่ยน Hitbox เป็น 40x40)
  if (my != YOFFSCREEN && boss_hp > 0) {
    if (in_rect(mx, my, boss_x, boss_y, 40, 40)) {
      missiles[PLYRMISSILE].ypos = YOFFSCREEN;
      if (boss_hp > 0) boss_hp--;
      
      // ให้ระเบิดเด้งออกมากึ่งกลางบอส
      vsprites[BOOMSPRITE].x = boss_x + 12;
      vsprites[BOOMSPRITE].y = boss_y + 12;
      vsprites[BOOMSPRITE].name = NAME_EXPLODE;
      
      draw_ui();
    }
  }

  if (player_invuln == 0) {
    // กระสุนบอสโดนผู้เล่น
    for (i = 0; i < NMISSILES - 1; i++) {
      if (missiles[i].ypos != YOFFSCREEN && 
          in_rect(missiles[i].xpos, missiles[i].ypos, player_x, player_y, 12, 12)) {
        
        missiles[i].ypos = YOFFSCREEN;
        if (player_hp > 0) player_hp--;
        player_invuln = 60;
        draw_ui();
        break;
      }
    }

    // ผู้เล่นชนบอส (เปลี่ยน Hitbox เป็น 40x40)
    if (boss_hp > 0 && in_rect(player_x, player_y, boss_x, boss_y, 40, 40)) {
      if (player_hp > 0) player_hp--;
      player_invuln = 60;
      draw_ui();
    }

    // ผู้เล่นโดนลำแสงบีบมุมตอนยิงเต็มเส้น
    if (player_in_laser()) {
      if (player_hp > 0) player_hp--;
      player_invuln = 60;
      draw_ui();
    }
  }
}

// --- ฟังก์ชันโหลดกราฟิกแบบเขียน 2 ชั้น (ผู้เล่น + บอสใหม่) ---
void setup_graphics() {
  ppu_off();

  // โหลดกราฟิกดั้งเดิมลง Pattern Table 0
  vram_adr(0x0000);
  vram_write(TILESET, sizeof(TILESET));
  // โหลดกราฟิกบอส 5x5 ต่อท้ายใน Pattern Table 0 (ที่ Index 96)
  vram_adr(0x0000 + (NAME_ENEMY * 16));
  vram_write(boss_tiles, sizeof(boss_tiles));
  // โหลดกราฟิกลำแสง (เส้นไกด์ + ลำแสงหนา) ที่ Index 121-122 ใน Pattern Table 0
  vram_adr(0x0000 + (NAME_LASER_THIN * 16));
  vram_write(laser_tiles, sizeof(laser_tiles));

  // โหลดกราฟิกดั้งเดิมลง Pattern Table 1
  vram_adr(0x1000);
  vram_write(TILESET, sizeof(TILESET));
  // โหลดกราฟิกบอส 5x5 ต่อท้ายใน Pattern Table 1 (ที่ Index 96)
  vram_adr(0x1000 + (NAME_ENEMY * 16));
  vram_write(boss_tiles, sizeof(boss_tiles));
  // โหลดกราฟิกลำแสงใน Pattern Table 1 ด้วยเช่นกัน
  vram_adr(0x1000 + (NAME_LASER_THIN * 16));
  vram_write(laser_tiles, sizeof(laser_tiles));

  ppu_on_all();
  vrambuf_clear();
  set_vram_update(updbuf);
}

void main() {  
  setup_graphics();
  apu_init();

  while (1) {
    pal_all(PALETTE);
    clrscr();

    player_x = 120;
    player_hp = 3;
    player_invuln = 0;
    boss_hp = BOSS_MAX_HP;
    boss_state = 0;
    boss_attack_pattern = 0;
    boss_y = 40;
    laser_phase = 0;
    laser_row = 0;
    laser_fire_timer = 0;
    
    clrobjs();
    draw_ui();

    // Game Loop
    while (player_hp > 0 && boss_hp > 0) {
      oam_clear();
      move_player();
      update_boss();
      update_laser();
      move_missiles();
      check_collisions();
      copy_sprites();

      ppu_wait_nmi();
      vrambuf_flush();
    }

    // End Game Screen
    clrscr();
    if (boss_hp == 0) {
      const char win_msg[8] = {CHAR('V'), CHAR('I'), CHAR('C'), CHAR('T'), CHAR('O'), CHAR('R'), CHAR('Y'), CHAR('!')};
      vrambuf_put(NTADR_A(11, 14), win_msg, 8);
    } else {
      const char lose_msg[9] = {CHAR('G'), CHAR('A'), CHAR('M'), CHAR('E'), CHAR(' '), CHAR('O'), CHAR('V'), CHAR('E'), CHAR('R')};
      vrambuf_put(NTADR_A(11, 14), lose_msg, 9);
    }
    vrambuf_flush();

    delay(180);
  }
}